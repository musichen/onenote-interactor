#!/usr/bin/env node
/**
 * create-markdown-only-book.cjs
 *
 * Interactively asks which book to export from exports/graph/,
 * then copies only .md files into exports/markdown/{book}/
 * preserving folder structure, with breadcrumb headers.
 * Also generates a {book}_index.md listing all files with stats.
 */

const fs = require("fs").promises;
const path = require("path");
const readline = require("readline");

const GRAPH_DIR = path.join(process.cwd(), "exports", "graph");
const MARKDOWN_DIR = path.join(process.cwd(), "exports", "markdown");

async function ensureDir(dir) {
  await fs.mkdir(dir, { recursive: true });
}

async function listBooks() {
  try {
    const entries = await fs.readdir(GRAPH_DIR, { withFileTypes: true });
    const books = [];
    for (const entry of entries) {
      if (entry.isDirectory() && !entry.name.startsWith(".")) {
        const pagesDir = path.join(GRAPH_DIR, entry.name, "pages");
        try {
          await fs.access(pagesDir);
          books.push(entry.name);
        } catch {
          // no pages dir, skip
        }
      }
    }
    return books.sort((a, b) => a.localeCompare(b));
  } catch (err) {
    console.error("Could not read exports/graph/:", err.message);
    process.exit(1);
  }
}

async function countMdFiles(bookName) {
  const pagesDir = path.join(GRAPH_DIR, bookName, "pages");
  let count = 0;
  async function walk(dir) {
    const entries = await fs.readdir(dir, { withFileTypes: true });
    for (const entry of entries) {
      const fullPath = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        await walk(fullPath);
      } else if (entry.isFile() && entry.name.endsWith(".md")) {
        count++;
      }
    }
  }
  await walk(pagesDir);
  return count;
}

function askQuestion(rl, question) {
  return new Promise((resolve) => {
    rl.question(question, (answer) => resolve(answer.trim()));
  });
}

function cleanMdFileName(fileName) {
  // Strip OneNote ID suffix like: -0-f52ee42107a1e04f9b83d3ab198f71df!1-BAAFF22D74E6C2C7!9165
  // Pattern: -0-<hex>!<digits>-<userId>!<pageId>
  // Examples: !1- !14- !21- !27- !28- !66- !146-
  return fileName.replace(/\-0-[0-9a-f]+![0-9]+-[0-9A-Za-z]+![0-9A-Za-z]+(?=\.md$)/, "");
}

async function copyMdWithBreadcrumb(bookName, onProgress) {
  const srcPagesDir = path.join(GRAPH_DIR, bookName, "pages");
  const destBookDir = path.join(MARKDOWN_DIR, bookName);
  await ensureDir(destBookDir);

  const copiedFiles = [];

  async function walk(srcDir) {
    const entries = await fs.readdir(srcDir, { withFileTypes: true });
    for (const entry of entries) {
      const srcPath = path.join(srcDir, entry.name);
      if (entry.isDirectory()) {
        await walk(srcPath);
      } else if (entry.isFile() && entry.name.endsWith(".md")) {
        // Compute relative path from srcPagesDir
        const relDir = path.relative(srcPagesDir, srcDir);
        const cleanName = cleanMdFileName(entry.name);
        const relPath = path.join(relDir, cleanName);
        const breadcrumb = path.posix.join(bookName, relPath).replace(/\\/g, "/");

        const destDir = path.join(destBookDir, relDir);
        await ensureDir(destDir);
        const destPath = path.join(destDir, cleanName);

        const originalContent = await fs.readFile(srcPath, "utf-8");
        const breadcrumbLine = `<!-- ${breadcrumb} -->\n`;
        const newContent = breadcrumbLine + originalContent;

        await fs.writeFile(destPath, newContent, "utf-8");
        copiedFiles.push({
          breadcrumb,
          relPath: relPath.replace(/\\/g, "/"),
          destPath: destPath.replace(/\\/g, "/"),
          srcPath: srcPath.replace(/\\/g, "/"),
        });

        if (onProgress) onProgress(breadcrumb);
      }
    }
  }

  await walk(srcPagesDir);
  return copiedFiles;
}

async function generateIndex(bookName, copiedFiles) {
  const now = new Date().toISOString();
  const total = copiedFiles.length;

  // Sort files by breadcrumb for consistent ordering
  copiedFiles.sort((a, b) => a.breadcrumb.localeCompare(b.breadcrumb));

  const lines = [];
  lines.push(`# ${bookName} — Markdown Export Index`);
  lines.push("");
  lines.push(`- **Export date:** ${now}`);
  lines.push(`- **Total markdown files:** ${total}`);
  lines.push("");
  lines.push("---");
  lines.push("");
  lines.push("## Files");
  lines.push("");

  for (const file of copiedFiles) {
    lines.push(`- \`${file.breadcrumb}\``);
  }

  lines.push("");
  lines.push("---");
  lines.push(`*Generated by create-markdown-only-book.cjs*`);

  const indexPath = path.join(MARKDOWN_DIR, bookName, `${bookName}_index.md`);
  await fs.writeFile(indexPath, lines.join("\n"), "utf-8");
  return indexPath;
}

async function main() {
  console.log("\n=== Markdown-Only Book Exporter ===\n");

  const books = await listBooks();
  if (books.length === 0) {
    console.log("No books found in exports/graph/");
    process.exit(0);
  }

  console.log("Available books:");
  books.forEach((book, i) => {
    console.log(`  ${i + 1}. ${book}`);
  });

  const rl = readline.createInterface({
    input: process.stdin,
    output: process.stdout,
  });

  let chosenBook = null;
  while (!chosenBook) {
    const answer = await askQuestion(rl, "\nEnter book number or name: ");
    const num = parseInt(answer, 10);
    if (!isNaN(num) && num >= 1 && num <= books.length) {
      chosenBook = books[num - 1];
    } else if (books.includes(answer)) {
      chosenBook = answer;
    } else {
      console.log("Invalid choice. Please enter a valid number or exact book name.");
    }
  }

  rl.close();

  console.log(`\nSelected book: "${chosenBook}"`);
  const mdCount = await countMdFiles(chosenBook);
  console.log(`Found ${mdCount} markdown file(s) in exports/graph/${chosenBook}/`);
  console.log(`\nCopying to exports/markdown/${chosenBook}/ ...\n`);

  const destBookDir = path.join(MARKDOWN_DIR, chosenBook);
  let processed = 0;
  const copiedFiles = await copyMdWithBreadcrumb(chosenBook, (breadcrumb) => {
    processed++;
    console.log(`  [${processed}/${mdCount}] ${breadcrumb}`);
  });

  const indexPath = await generateIndex(chosenBook, copiedFiles);

  // Validation: scan for any files that still have uncleaned IDs
  const idPattern = /\-0-[0-9a-f]+![0-9]+-[0-9A-Za-z]+![0-9A-Za-z]+\.md$/;
  const remainingUncleaned = [];
  async function validateDir(dir) {
    const entries = await fs.readdir(dir, { withFileTypes: true });
    for (const entry of entries) {
      const fullPath = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        await validateDir(fullPath);
      } else if (entry.isFile() && idPattern.test(entry.name)) {
        remainingUncleaned.push(path.relative(destBookDir, fullPath).replace(/\\/g, "/"));
      }
    }
  }
  await validateDir(destBookDir);

  if (remainingUncleaned.length > 0) {
    console.log(`\n⚠️  WARNING: ${remainingUncleaned.length} file(s) still have uncleaned OneNote IDs:`);
    for (const f of remainingUncleaned.slice(0, 20)) {
      console.log(`     ${f}`);
    }
    if (remainingUncleaned.length > 20) {
      console.log(`     ... and ${remainingUncleaned.length - 20} more`);
    }
  }

  console.log(`\n✅ Done!`);
  console.log(`   Copied: ${copiedFiles.length} markdown file(s)`);
  console.log(`   Destination: ${path.join(MARKDOWN_DIR, chosenBook)}`);
  console.log(`   Index: ${indexPath}`);
  if (remainingUncleaned.length === 0) {
    console.log(`   Validation: all filenames cleaned ✓`);
  }
}

main().catch((err) => {
  console.error("Fatal error:", err);
  process.exit(1);
});
